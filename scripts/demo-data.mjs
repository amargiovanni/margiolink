/**
 * The demo dataset, as data.
 *
 * Pure and deterministic: no I/O, no `node:` imports, no `Date.now()`, no
 * `Math.random()`. Everything comes from the caller's `now` and a fixed-seed
 * PRNG, so the same arguments produce byte-identical rows on any machine —
 * which is what makes the screenshots in `docs/screenshots/` reproducible
 * rather than a snapshot of one afternoon's luck.
 *
 * Purity is also why this file is a sibling of `seed-demo.mjs` rather than
 * part of it: `test/demo-seed.test.ts` imports it inside `workerd`, inserts
 * what it returns into a real D1, and runs the real rollup and the real
 * dashboard queries over the result. A generator that reached for the
 * filesystem or a subprocess could not be tested that way.
 *
 * ## Why this writes rows instead of firing requests
 *
 * `e2e/seed.ts` deliberately builds its fixtures through the public HTTP API,
 * which makes it a test of that API. It also documents the two things that
 * approach provably cannot vary (its own module comment): `request.cf` is
 * fetched once per `wrangler dev` process, so every click carries the same
 * country, and a click's timestamp is computed inside the Worker, so every
 * click lands today. One country and one day are exactly the two axes a
 * screenshot of a world map and a 180-day chart needs.
 *
 * So this generator is the other half of the pair, with the opposite
 * trade-off stated plainly: it fabricates rows, it is not a test of the
 * ingestion path, and it must therefore keep its column set in step with
 * `src/db/clicks.ts` by hand. `test/demo-seed.test.ts` pins that in both
 * directions so "by hand" means "with a failing test when it drifts", the
 * same guard `test/compliance.test.ts` puts on the data map.
 */

