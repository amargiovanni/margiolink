/** Weighted pick over `[{weight, ...}]`, with an optional per-item multiplier
 *  so a link can bend a shared pool (more mobile on a QR poster, more email
 *  on a newsletter) without needing a pool of its own. */
function pick(random, pool, multiplier) {
  let total = 0;
  for (const item of pool) total += multiplier ? item.weight * multiplier(item) : item.weight;
  let roll = random() * total;
  for (const item of pool) {
    roll -= multiplier ? item.weight * multiplier(item) : item.weight;
    if (roll <= 0) return item;
  }
  return pool[pool.length - 1];
}

/** 32 hex characters, the same width `visitorHash` in `src/lib/crypto.ts`
 *  produces (an HMAC-SHA-256 truncated to 16 bytes). Not a hash of anything —
 *  see the module comment on what this generator is and is not. */
function fakeHash(random) {
  let out = "";
  for (let i = 0; i < 32; i++) out += "0123456789abcdef"[Math.floor(random() * 16)];
  return out;
}

function utcDay(ts) {
  return new Date(ts * 1000).toISOString().slice(0, 10);
}

/**
 * Build the whole dataset.
 *
 * @param {object} options
 * @param {number} options.now      Unix seconds the window ends at (exclusive-ish: the
 *                                  final day is partial, as a real "today" is).
 * @param {number} [options.days]   Length of the window. The default is
 *                                  `RAW_RETENTION_DAYS`, so the dashboard's
 *                                  longest offered period has both its own
 *                                  span and its comparison window populated.
 * @param {number} [options.seed]   PRNG seed. Change it for a different but
 *                                  equally reproducible dataset.
 */
export function generateDemoData({ now, days = 180, seed = 20260903 } = {}) {
  if (!Number.isFinite(now)) throw new Error("generateDemoData: `now` must be a Unix timestamp");
  if (!Number.isInteger(days) || days < 1)
    throw new Error("generateDemoData: `days` must be a positive integer");

  const random = mulberry32(seed);
  // Midnight UTC of the oldest day in the window, so every day boundary in
  // the output lines up with the boundaries `rollupDay` and the dashboard's
  // date filters use.
  const startOfToday = Math.floor(now / DAY) * DAY;
  const windowStart = startOfToday - (days - 1) * DAY;

  /** A fraction of the window as a day index inside it. `undefined` stays
   *  `undefined` — the difference between "expires on day 128" and "never
   *  expires" has to survive the conversion. */
  const dayOf = (fraction) =>
    fraction === undefined ? undefined : Math.min(days - 1, Math.round(fraction * days));

  const schedule = new Map(
    LINKS.map((link) => [
      link.id,
      {
        start: dayOf(link.startAt) ?? 0,
        expires: dayOf(link.expiresAt),
        inactiveFrom: dayOf(link.inactiveFrom),
        deleted: dayOf(link.deletedAt),
      },
    ]),
  );

  const links = LINKS.map((link) => {
    const when = schedule.get(link.id);
    const createdAt = windowStart + when.start * DAY + Math.floor(random() * DAY);
    return {
      id: link.id,
      slug: link.slug,
      targetUrl: link.targetUrl,
      title: link.title,
      description: link.description ?? null,
      password: link.password ?? null,
      expiresAt: when.expires === undefined ? null : windowStart + when.expires * DAY,
      expiredUrl: link.expiredUrl ?? null,
      isActive: when.inactiveFrom === undefined ? 1 : 0,
      createdAt,
      updatedAt:
        when.inactiveFrom === undefined ? createdAt : windowStart + when.inactiveFrom * DAY,
      deletedAt: when.deleted === undefined ? null : windowStart + when.deleted * DAY,
    };
  });

  const linkTags = LINKS.flatMap((link) =>
    link.tagIds.map((tagId) => ({ linkId: link.id, tagId })),
  );

  const clicks = [];

  for (const link of LINKS) {
    const when = schedule.get(link.id);
    const life = days - when.start;
    // A link soft-deleted mid-window stops collecting the day it happens: a
    // deleted slug 404s before `recordClick` is ever called
    // (`src/routes/redirect.ts`). An expired one keeps recording — it still
    // answers, with outcome `expired` — so only the deleted case truncates.
    const lastDay = when.deleted === undefined ? days : when.deleted;

    for (let day = when.start; day < lastDay; day++) {
      const dayStart = windowStart + day * DAY;
      const weekday = (new Date(dayStart * 1000).getUTCDay() + 6) % 7;
      // Age through the link's own life, 0 at creation and 1 at the end of
      // the window — what `shape` is a function of.
      const age = life <= 1 ? 1 : (day - when.start) / (life - 1);

      const expected =
        link.weight *
        link.shape(age) *
        WEEKDAY_WEIGHTS[weekday] *
        // Site-wide growth: the whole project is bigger in month six than in
        // month one, on top of whatever each link is doing individually.
        (0.55 + 0.9 * (day / days)) *
        // Day-to-day noise, so no two days are the same height.
        (0.72 + 0.56 * random());

      // The last day of the window is "today", and today is only as far
      // through as `now` says it is. Without this the final bar of every
      // chart is a cliff — a full day's traffic recorded by mid-morning.
      const partial = day === days - 1 ? Math.max(0.05, (now - startOfToday) / DAY) : 1;

      const count = Math.max(0, Math.round(expected * partial));
      if (count === 0) continue;

      // Visitors, not clicks: roughly two in three clicks are somebody's
      // first of the day, the rest are the same person coming back. The
      // dashboard's unique count is `COUNT(DISTINCT visitor_hash)` within a
      // day, and a real one is always below the click count.
      const pool = [];
      const poolTarget = Math.max(1, Math.round(count * 0.68));

      for (let i = 0; i < count; i++) {
        const hour = pick(
          random,
          HOUR_WEIGHTS.map((weight, index) => ({ weight, index })),
        ).index;
        const ts = dayStart + hour * 3600 + Math.floor(random() * 3600);
        if (ts >= now) continue;

        const place = pick(random, PLACES);
        const client = pick(random, CLIENTS, (item) =>
          link.mobileBias && item.deviceType === "mobile" ? link.mobileBias : 1,
        );
        const referrer = pick(random, REFERRERS, (item) => link.channels?.[item.type] ?? 1);

        const visitorHash =
          pool.length < poolTarget || random() < 0.5
            ? (() => {
                const fresh = fakeHash(random);
                pool.push(fresh);
                return fresh;
              })()
            : pool[Math.floor(random() * pool.length)];

        // Outcome follows the link's own state at that moment, exactly as the
        // redirect route decides it. An expired link with an `expired_url`
        // still records `expired` — it redirects onward, but not to the
        // original target.
        let outcome = "redirect";
        if (when.inactiveFrom !== undefined && day >= when.inactiveFrom) outcome = "inactive";
        else if (when.expires !== undefined && day >= when.expires) outcome = "expired";
        else if (link.password) {
          const roll = random();
          // Most arrivals see the interstitial; a few get the password wrong;
          // the rest are the same people coming back through with a valid
          // ten-minute cookie.
          outcome =
            roll < 0.58 ? "password_required" : roll < 0.68 ? "password_failed" : "redirect";
        }

        const isBot = client.bot === true;
        // A crawler carries no referrer, no campaign and no language — it is
        // a bare GET. Recording one with a `linkedin.com` referrer would be a
        // row no real crawler ever produces.
        const utm = isBot ? null : link.utm;

        clicks.push({
          linkId: link.id,
          ts,
          visitorHash,
          source: !isBot && link.qrShare && random() < link.qrShare ? "qr" : "link",
          outcome,
          isBot: isBot ? 1 : 0,
          continent: place.continent,
          country: place.country,
          region: place.region,
          city: place.city,
          timezone: place.timezone,
          asnOrg: isBot ? "Google LLC" : place.asnOrg,
          colo: place.colo,
          deviceType: client.deviceType,
          os: client.os,
          osVersion: client.osVersion,
          browser: client.browser,
          browserVersion: client.browserVersion,
          language: isBot ? null : place.language,
          referrerHost: isBot ? null : referrer.host,
          referrerType: isBot ? "direct" : referrer.type,
          utmSource: utm?.source ?? null,
          utmMedium: utm?.medium ?? null,
          utmCampaign: utm?.campaign ?? null,
          utmTerm: null,
          utmContent: null,
        });
      }
    }
  }

  // Chronological, so a `LIMIT`ed read of the raw table during development
  // shows a coherent slice rather than one link's whole history.
  clicks.sort((a, b) => a.ts - b.ts || a.linkId - b.linkId);

  return {
    tags: TAGS,
    links,
    linkTags,
    clicks,
    window: {
      from: windowStart,
      to: now,
      days,
      firstDay: utcDay(windowStart),
      lastDay: utcDay(now),
    },
  };
}
