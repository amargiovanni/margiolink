/**
 * mulberry32 — 32 bits of state, uniform enough for sampling weighted pools
 * and small enough to read. Not for anything that needs to be unguessable:
 * this file never produces a secret, and the one real password in the dataset
 * is a literal (`DEMO_PASSWORD`) precisely so nobody mistakes generated bytes
 * for entropy.
 */
function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4_294_967_296;
  };
}

